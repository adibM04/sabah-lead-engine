// Turns migrations/*.sql into functions/_lib/migrations.generated.ts so the app can bring its own
// database up to date (see functions/_lib/migrate.ts). Runs before every build.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Split SQL into statements: drops comments, respects quotes, keeps CREATE TRIGGER ... END; whole. */
export function split(sql) {
  const out = [];
  let cur = "";
  let quote = null;
  for (let i = 0; i < sql.length; i++) {
    const c = sql[i];
    if (quote) {
      cur += c;
      if (c === quote) quote = null;
      continue;
    }
    if (c === "-" && sql[i + 1] === "-") {
      while (i < sql.length && sql[i] !== "\n") i++;
      cur += "\n";
      continue;
    }
    if (c === "'" || c === '"') {
      quote = c;
      cur += c;
      continue;
    }
    if (c === ";") {
      const text = cur.trim();
      const isTrigger = /^create\s+(temp\s+|temporary\s+)?trigger\b/i.test(text);
      if (isTrigger && !/\bend\s*$/i.test(text)) {
        cur += c;
        continue;
      }
      if (text) out.push(text.replace(/\s+/g, " "));
      cur = "";
      continue;
    }
    cur += c;
  }
  if (cur.trim()) out.push(cur.trim().replace(/\s+/g, " "));
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = readdirSync(join(root, "migrations")).filter((f) => f.endsWith(".sql")).sort();
  const list = files.map((name) => ({ name, statements: split(readFileSync(join(root, "migrations", name), "utf8")) }));
  const body =
    "// Generated by scripts/gen-migrations.mjs from migrations/*.sql. Do not edit by hand.\n" +
    "export const MIGRATIONS: { name: string; statements: string[] }[] = " +
    JSON.stringify(list, null, 1) +
    ";\n";
  writeFileSync(join(root, "functions/_lib/migrations.generated.ts"), body);
  console.log(`migrations: ${list.map((m) => `${m.name} (${m.statements.length})`).join(", ")}`);
}
